/**
 * Writes the OpenAPI document for `AuditApi` to `docs/api/openapi.json` and a generated endpoint
 * table to `docs/api/endpoints.md`. Run by `bun run docs:openapi` (and therefore `docs:build`).
 */
import { AuditApi } from "../src/api.ts"
import { OpenApi } from "effect/http-api"
import { writeFile } from "node:fs/promises"
import { join } from "node:path"

const root = join(import.meta.dir, "..", "..", "..", "docs", "api")
const spec = OpenApi.fromApi(AuditApi) as unknown as {
  paths: Record<string, Record<string, { summary?: string; tags?: ReadonlyArray<string> }>>
}

const rows: string[] = []
for (const [path, methods] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b))) {
  for (const [method, op] of Object.entries(methods)) {
    const tag = op.tags?.[0] ?? ""
    rows.push(`| \`${method.toUpperCase()}\` | \`${path}\` | ${tag} | ${op.summary ?? ""} |`)
  }
}

await writeFile(join(root, "openapi.json"), `${JSON.stringify(spec, null, 2)}\n`)
await writeFile(
  join(root, "endpoints.md"),
  [
    "<!-- Generated by scripts/docs-openapi.ts. Do not edit. -->",
    "",
    `# Endpoint table (${rows.length} operations)`,
    "",
    "| Method | Path | Group | Summary |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n"),
)
console.log(`wrote ${rows.length} operations`)
