-- Append-only: updates are rejected, except that a pending row gets its chain fields once, from the
-- chainer. Deletes happen only inside trail_purge().
CREATE OR REPLACE FUNCTION trail_events_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND coalesce(current_setting('audit.trail_purge', true), '') = 'on' THEN
    RETURN OLD;
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.chain_pos IS NULL AND NEW.chain_pos IS NOT NULL AND NEW.hash IS NOT NULL
    AND (to_jsonb(NEW) - 'chain_pos' - 'prev_hash' - 'hash') = (to_jsonb(OLD) - 'chain_pos' - 'prev_hash' - 'hash')
  THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'trail_events is append-only' USING ERRCODE = 'insufficient_privilege';
END
$$;--> statement-breakpoint
