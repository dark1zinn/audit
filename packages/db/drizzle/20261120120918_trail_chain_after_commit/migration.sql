-- Chains pending entries in commit order. One chainer at a time (advisory lock held to the end of
-- the call), so chain positions are dense and each entry links to the one before it. Runs with the
-- owner's rights: the app login may chain, but not rewrite entries.
CREATE FUNCTION trail_chain(key text, batch integer) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  pending trail_events%ROWTYPE;
  position bigint;
  previous text;
  chained integer := 0;
BEGIN
  IF coalesce(key, '') = '' THEN
    RAISE EXCEPTION 'trail key is required' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  IF batch IS NULL OR batch < 1 THEN
    RAISE EXCEPTION 'trail chain batch must be positive' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('audit:trail_chain'));
  SELECT chain_pos, hash INTO position, previous FROM trail_events
    WHERE chain_pos IS NOT NULL ORDER BY chain_pos DESC LIMIT 1;
  position := coalesce(position, 0);
  FOR pending IN SELECT * FROM trail_events WHERE chain_pos IS NULL ORDER BY seq LIMIT batch LOOP
    position := position + 1;
    pending.chain_pos := position;
    pending.prev_hash := previous;
    pending.hash := trail_event_mac(pending, key);
    UPDATE trail_events
      SET chain_pos = pending.chain_pos, prev_hash = pending.prev_hash, hash = pending.hash
      WHERE id = pending.id;
    previous := pending.hash;
    chained := chained + 1;
  END LOOP;
  RETURN chained;
END
$$;--> statement-breakpoint
