-- Retention: the only path that deletes trail rows. The floor matches the app's minimum (30 days).
-- Removes chained entries before the first one inside the window, never pending ones and never the
-- head, then pins the new chain start in trail_anchor.
CREATE OR REPLACE FUNCTION trail_purge(retention_days integer) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  removed bigint;
  cut bigint;
  chain_head bigint;
  kept_pos_value bigint;
  kept_prev_hash_value text;
BEGIN
  IF retention_days IS NULL OR retention_days < 30 THEN
    RAISE EXCEPTION 'trail retention must be at least 30 days' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  SELECT max(chain_pos) INTO chain_head FROM trail_events;
  IF chain_head IS NULL THEN
    RETURN 0;
  END IF;
  SELECT min(chain_pos) INTO cut FROM trail_events
    WHERE chain_pos IS NOT NULL AND at >= now() - make_interval(days => retention_days);
  cut := least(coalesce(cut, chain_head + 1), chain_head);
  PERFORM set_config('audit.trail_purge', 'on', true);
  DELETE FROM trail_events WHERE chain_pos < cut;
  GET DIAGNOSTICS removed = ROW_COUNT;
  PERFORM set_config('audit.trail_purge', 'off', true);
  IF removed > 0 THEN
    DELETE FROM trail_anchor;
    SELECT chain_pos, prev_hash INTO kept_pos_value, kept_prev_hash_value FROM trail_events
      WHERE chain_pos IS NOT NULL ORDER BY chain_pos LIMIT 1;
    INSERT INTO trail_anchor (kept_pos, kept_prev_hash, purged)
      VALUES (kept_pos_value, kept_prev_hash_value, removed);
  END IF;
  RETURN removed;
END
$$;
